const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../management.js'),'utf8');
const start=src.indexOf('function renderManagementKpis()');
const end=src.indexOf('function managementGoalCard(',start);
assert.ok(start>=0&&end>start);
let result='';
const root={set innerHTML(v){result=v},get innerHTML(){return result}};
const state={managementOverview:{metrics:{revenue:2272376.84,revenue_change_percent:11.5},goals:[{goal_type:'revenue',period_type:'week',starts_at:'2026-10-05T22:00:00Z',ends_at:'2026-10-12T22:00:00Z',current_value:2126572.76}]}};
const ctx={state,document:{getElementById:()=>root},Date,Number,money:n=>Number(n||0).toFixed(2),balanceMoney:n=>String(n),managementNumber:n=>String(n),managementValueTone:()=>'',num:String};
vm.createContext(ctx);
vm.runInContext(src.slice(start,end),ctx);
ctx.renderManagementKpis();
assert.ok(result.includes('2126572.76'),'KPI should match active weekly goal');
assert.ok(!result.includes('2272376.84'),'Rolling total should not replace weekly goal');
state.managementOverview.goals=[];
ctx.renderManagementKpis();
assert.ok(result.includes('2272376.84'),'Without an active goal show rolling 7-day metric');
console.log('Management revenue period consistency passed.');
